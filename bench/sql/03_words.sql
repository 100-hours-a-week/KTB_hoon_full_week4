CREATE TABLE bench_word_pool (
    topic INT NOT NULL,
    slot  INT NOT NULL,
    word  VARCHAR(20) NOT NULL,
    PRIMARY KEY (topic, slot)
) ENGINE=InnoDB;

INSERT INTO bench_word_pool (topic, slot, word)
SELECT w.topic, ROW_NUMBER() OVER (PARTITION BY w.topic ORDER BY w.id, r.n), w.word
FROM bench_words w
JOIN numbers r ON r.n <= w.weight;

CREATE TABLE bench_topic_pool_size (
    topic INT NOT NULL PRIMARY KEY,
    sz    INT NOT NULL
) ENGINE=InnoDB;

INSERT INTO bench_topic_pool_size (topic, sz)
SELECT topic, COUNT(*) FROM bench_word_pool GROUP BY topic;

SELECT topic, sz FROM bench_topic_pool_size ORDER BY topic LIMIT 5;
SELECT COUNT(*) AS distinct_words, SUM(weight) AS total_slots FROM bench_words;
